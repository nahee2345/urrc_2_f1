#!/usr/bin/env python3
"""Six-track TEAM08 blind-world-identification qualifying rehearsal.

The requested circuit is passed to the official operator runner ONLY.
No track name, track path, or lane selection is supplied to TEAM08.
Runs interactive READY for each track; reports factual evidence, not fake PASS.
"""
from __future__ import annotations

import argparse
from datetime import datetime
import json
import os
from pathlib import Path
import re
import subprocess
import sys

TRACKS = ("monza", "spa", "monaco", "cota", "hungaroring", "baku")
LAPS = 3
MAP_RE = re.compile(r"BattleReplay08 core active map=([a-z_]+)")
# Generated by the official operator for every rehearsal, not our own report.
PREVIEW_RE = "v17_qualifying_*"


def preview_directories(root: Path) -> set[Path]:
    return {p.resolve() for p in (root / "race" / "previews").glob(PREVIEW_RE) if p.is_dir()}


def check_result(track: str, folder: Path | None, exit_code: int) -> dict:
    row = dict(track=track, exit_code=exit_code, status="FAIL",
               official_preview=str(folder) if folder else None)
    if folder is None:
        row["reason"] = "official rehearsal did not create a unique output folder"
        return row
    report = folder / "report.json"
    if not report.is_file():
        row["reason"] = "official report.json missing"
        return row
    try:
        data = json.loads(report.read_text(encoding="utf-8"))
    except (ValueError, OSError) as exc:
        row["reason"] = "invalid official report: " + str(exc)
        return row
    detail = data.get("details", {}).get("team_08", {})
    row.update(
        official_status=data.get("status"),
        team_status=detail.get("status"),
        observed_laps=detail.get("laps", 0),
        sensor_status=data.get("sensor_status", "not reported"),
    )
    # Official ROS launch log is authoritative about which internal
    # circuit TEAM08 chose after the Gazebo world was spawned.
    logs = sorted(folder.glob("team_08*algorithm*.log"))
    chosen = []
    for log in logs:
        chosen.extend(MAP_RE.findall(log.read_text(encoding="utf-8", errors="replace")))
    row["team08_detected_world"] = chosen[-1] if chosen else None
    checks = (
        exit_code == 0,
        data.get("status") == "OBSERVATION_COMPLETE",
        detail.get("status") == "PASS",
        int(detail.get("laps") or 0) >= LAPS,
        bool(chosen),
        all(name == track for name in chosen),
    )
    if all(checks):
        row["status"] = "PASS"
    else:
        row["reason"] = "failed checks: " + ", ".join(
            name for name, ok in zip(
                ("process exit", "official observation", "team result",
                 "three laps", "world detected", "world agrees with operator"),
                checks) if not ok
        )
    return row


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--workspace", type=Path,
                        default=Path.home() / "urrc_f1_ws")
    parser.add_argument("--seconds", type=int, default=600)
    parser.add_argument("--tracks", nargs="+", choices=TRACKS,
                        default=list(TRACKS))
    args = parser.parse_args()
    root = args.workspace.expanduser().resolve()
    if not (root / "race_v24.sh").is_file():
        parser.error("official race_v24.sh missing in " + str(root))
    if not (root / "race/install/setup.bash").is_file():
        parser.error("run bash race_v24.sh sync && bash race_v24.sh prepare first")
    result_rows = []
    result_path = root / "race" / "results" / (
        "team08_blind_6track_" + datetime.now().strftime("%Y%m%d_%H%M%S") + ".json"
    )
    print("TEAM08 blind-map test: only official operator receives --track.")
    print("Each qualifying rehearsal spawns TEAM08 alone at grid position 1.")
    print("The team gets no command line track name; it reads Gazebo World.")
    print("Enter READY separately for each requested map.", flush=True)
    for track in args.tracks:
        print("\n========== " + track.upper() + " ==========", flush=True)
        before = preview_directories(root)
        cmd = ["bash", "race_v24.sh", "rehearse", "qualifying",
               "--track", track, "--team", "team_08",
               "--seconds", str(args.seconds), "--start-mode", "signal"]
        try:
            status = subprocess.run(cmd, cwd=root, check=False).returncode
        except KeyboardInterrupt:
            status = 130
        created = preview_directories(root) - before
        folder = max(created, key=lambda p: p.stat().st_mtime) if len(created) == 1 else None
        row = check_result(track, folder, status)
        result_rows.append(row)
        result_path.parent.mkdir(parents=True, exist_ok=True)
        result_path.write_text(json.dumps(result_rows, ensure_ascii=False, indent=2) + "\n",
                               encoding="utf-8")
        print(f"[BLIND-TEST] {track}: {row['status']} "
              f"world={row.get('team08_detected_world')} "
              f"laps={row.get('observed_laps')} "
              f"sensor={row.get('sensor_status')}", flush=True)
        if row["status"] != "PASS":
            print("[BLIND-TEST] STOP: " + row.get("reason", "unknown error"), flush=True)
            break
    print("\nResults: " + str(result_path), flush=True)
    print(f"PASS {sum(x['status']=='PASS' for x in result_rows)}/{len(args.tracks)}",flush=True)
    return 0 if len(result_rows) == len(args.tracks) and all(
        x["status"] == "PASS" for x in result_rows) else 1


if __name__ == "__main__":
    sys.exit(main())
