#!/usr/bin/env python3
"""Manual practice only. Focus this window and use English input."""

import tkinter as tk
import rclpy
from rclpy.node import Node
from std_msgs.msg import Float32


class WadsTeleop(Node):
    def __init__(self):
        super().__init__("team11_wads_teleop")

        self.speed_pub = self.create_publisher(
            Float32, "/team_11/speed", 10
        )

        self.steer_pub = self.create_publisher(
            Float32, "/team_11/steering", 10
        )

        self.held = set()
        self.releases = {}
        self.closed = False

        self.root = tk.Tk()
        self.root.title("URRC W A S D")

        tk.Label(
            self.root,
            padx=24,
            pady=24,
            text=(
                "W: forward / S: reverse\n"
                "A: left / D: right\n"
                "W+A or W+D: drive and steer\n"
                "Space: stop / Esc: close"
            ),
        ).pack()

        self.root.bind_all("<KeyPress>", self.key_down)
        self.root.bind_all("<KeyRelease>", self.key_up)
        self.root.bind("<FocusOut>", lambda event: self.stop())
        self.root.protocol("WM_DELETE_WINDOW", self.close)

        self.root.after(50, self.tick)

    def key_down(self, event):
        key = event.keysym.lower()

        pending = self.releases.pop(key, None)

        if pending is not None:
            self.root.after_cancel(pending)

        if key in ("w", "a", "s", "d"):
            self.held.add(key)

        elif key == "space":
            self.stop()

        elif key == "escape":
            self.close()

    def key_up(self, event):
        key = event.keysym.lower()

        # Ignore synthetic release/press pairs generated by key repeat.
        if key not in self.releases:
            self.releases[key] = self.root.after_idle(
                self.release, key
            )

    def release(self, key):
        self.releases.pop(key, None)
        self.held.discard(key)

    def publish(self, speed, steer):
        self.speed_pub.publish(
            Float32(data=float(speed))
        )

        self.steer_pub.publish(
            Float32(data=float(steer))
        )

    def stop(self):
        self.held.clear()
        self.publish(0.0, 0.0)

    def tick(self):
        if self.closed:
            return

        speed = 0.0

        if "w" in self.held and "s" not in self.held:
            speed = 0.6

        elif "s" in self.held and "w" not in self.held:
            speed = -0.3

        steer = 0.45 * (
            ("d" in self.held) - ("a" in self.held)
        )

        self.publish(speed, steer)

        self.root.after(50, self.tick)

    def close(self):
        if not self.closed:
            self.stop()
            self.closed = True
            self.root.destroy()


def main():
    rclpy.init()

    node = WadsTeleop()

    try:
        node.root.mainloop()

    except KeyboardInterrupt:
        pass

    finally:
        if rclpy.ok():
            node.publish(0.0, 0.0)

        node.destroy_node()

        if rclpy.ok():
            rclpy.shutdown()


if __name__ == "__main__":
    main()